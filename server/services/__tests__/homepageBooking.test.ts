import assert from "node:assert/strict";
import { bookingDateTimeToUtc, bookingTimeLabel, movePlanSchema, recommendMove, validBookingDate } from "../../../shared/homepageBooking";
import { publicInstantQuote, publicRequestHash } from "../publicBookingRequests";
const plan = movePlanSchema.parse({ sizingBasis: "truck", truckSize: "26_ft", scope: "load", inventory: "Boxes and a sofa" });
const recommended = recommendMove(plan);
assert.equal(recommended.crewSize, 4);
assert.equal(recommended.maximumHours, 4);
const override = recommendMove({ ...plan, selectedCrewSize: 2, selectedHours: 4, overrideReason: "Only a partial load" });
assert.equal(override.selectedCrewSize, 2);
assert.equal(override.selectedHours, 4);
assert.equal(override.overridden, true);
assert.equal(override.reviewRequired, true);
assert.equal(recommendMove({ ...plan, selectedCrewSize: 2 }).selectedHours, 8, "26-foot/two-mover/four-hour is not a fixed rule");
for (const date of ["", "tomorrow", "2026-02-30", "2026-13-01"]) assert.equal(validBookingDate(date), false);
assert.equal(validBookingDate("2028-02-29"), true);
assert.throws(() => bookingDateTimeToUtc("2026-02-30", "10:00"));
assert.equal(bookingDateTimeToUtc("2026-07-10", "10:00").toISOString(), "2026-07-10T15:00:00.000Z");
assert.equal(bookingDateTimeToUtc("2026-12-10", "10:00").toISOString(), "2026-12-10T16:00:00.000Z");
assert.equal(bookingDateTimeToUtc("2026-11-01", "10:00").toISOString(), "2026-11-01T16:00:00.000Z");
assert.match(bookingTimeLabel("2026-07-10T15:00:00Z", "America/Chicago"), /10:00 AM CDT/);
assert.match(bookingTimeLabel("2026-07-10T15:00:00Z", "America/Detroit"), /11:00 AM EDT/);
const quote = { minEstimate: 555, maxEstimate: 555, crewSize: 3, requestedHours: 2, pricingVersion: "fixture", lineItems: [], ownerProfit: 999, employeePay: 111, routeEvidence: { private: true } };
const publicQuote = publicInstantQuote(quote);
assert.equal("ownerProfit" in publicQuote, false);
assert.equal("employeePay" in publicQuote, false);
assert.equal("routeEvidence" in publicQuote, false);
assert.notEqual(publicQuote.fingerprint, publicInstantQuote({ ...quote, minEstimate: 556 }).fingerprint);
assert.notEqual(publicQuote.fingerprint, publicInstantQuote({ ...quote, crewSize: 2 }).fingerprint);
assert.equal(publicRequestHash("a").length, 64);
console.log("Homepage booking: advisory selections, date validation, Central/Eastern DST and customer quote projection passed");
